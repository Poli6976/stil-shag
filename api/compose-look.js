/* Возвращает true, если картинку стоит перегенерировать. Любая проблема на этом шаге (сеть, лимит,
   странный ответ) НЕ должна ломать уже готовый результат — тогда просто считаем, что картинка сойдёт
   как есть (мягкий отказ, тот же принцип, что и у самопроверки текста выше).
   originalFileId — id уже загруженного в GigaChat фото клиентки (см. handler ниже, оно грузится один
   раз для разбора вещи и переиспользуется здесь) — передаётся только когда картинку рисовал Kontext,
   чтобы включить прямое сравнение с реальным фото вместо текстовой проверки размера. */
async function imageNeedsRetry(token, imageBase64, fit, layers, originalFileId) {
  var verifyFileId = await uploadFile(token, Buffer.from(imageBase64, 'base64'), 'image/jpeg');
  var bothPhotos = !!originalFileId;
  var bodyPhrase = !bothPhotos && fit ? sizeToBodyPhrase(extractClothingSize(fit)) : null;
  var attachments = bothPhotos ? [originalFileId, verifyFileId] : verifyFileId;
  var verdict = await chatWithImage(
    token,
    buildImageVerifyPrompt(bodyPhrase, layers, bothPhotos),
    'Проверь эту картинку.',
    attachments
  );
  return verdict.trim().toUpperCase().indexOf('OK') !== 0;
}

/* Строку "эта же вещь"/"та же вещь" GigaChat иногда пишет вопреки прямому запрету в SYSTEM_PROMPT
   (та же нестабильность, что и с курткой/рубашкой) — если это попадёт в слой, который НЕ совпадает
   с "Реальная вещь", получится картинка вроде "Низ: эта же вещь" для футболки: бессмысленная фраза
   уходит в промпт наравне с остальными слоями и ломает результат. Отфильтровываем на уровне кода,
   а не полагаемся только на инструкцию — слой просто не попадёт ни на экран, ни в промпт картинки.

   2026-09-16 — regex ловил только ТОЧНОЕ совпадение ("эта же вещь." и больше ничего). Живой тест
   показал строку "Низ: Эта же вещь: Пиджак катоновый." — GigaChat всё равно сослался на "эта же
   вещь", но приписал следом ещё и описание, так что точный фильтр её пропустил, и вся фраза целиком
   (включая бессмысленную ссылку) ушла в промпт картинки. Меняю на префиксный фильтр: отрезаем саму
   фразу-ссылку, если она встречается как заголовок значения, и оставляем то, что осталось (если
   осталось — это реальное описание вещи; если нет — слой просто не заполнится, как и раньше). Не
   чинит смысловую ошибку классификации (пиджак вообще не должен быть в "Низ" — это отдельная,
   более сложная проблема GigaChat), но не даёт мусорной фразе-ссылке протечь в промпт. */
var SAME_ITEM_PREFIX_RE = /^(эта|та)\s+же\s+вещь\.?\s*[:.,]?\s*/i;

function parseLayers(text) {
  var layers = {};
  var why = '';
  var gender = 'female'; // дефолт сайта, если строку "Пол" не прислали вовсе
  var realKey = null;
  text.split('\n').forEach(function (line) {
    var idx = line.indexOf(':');
    if (idx === -1) return;
    var key = line.slice(0, idx).trim();
    var value = line.slice(idx + 1).trim();
    if (!value) return;
    if (key === 'Почему') { why = value; return; }
    if (key === 'Пол') { gender = /муж/i.test(value) ? 'male' : 'female'; return; }
    if (key === 'Реальная вещь') { if (LAYER_KEYS.indexOf(value) !== -1) realKey = value; return; }
    if (LAYER_KEYS.indexOf(key) !== -1) {
      var cleaned = value.replace(SAME_ITEM_PREFIX_RE, '').trim();
      if (cleaned) layers[key] = cleaned;
    }
  });
  return { layers: layers, why: why, gender: gender, realKey: realKey };
}

