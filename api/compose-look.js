var SAME_ITEM_PREFIX_RE = /^(эта|та)\s+же\s+вещь\.?\s*[:.,]?\s*/i;

function parseLayers(text) {
  var layers = {};
  var why = '';
  var gender = 'female'; // дефолт сайта, если строку "Пол" не прислали вовсе
  var realKey = null;
  text.split('\n').forEach(function (line) {
    var idx = line.indexOf(':');
    if (idx === -1) return;
    var key = line.slice(0, idx).trim();
    var value = line.slice(idx + 1).trim();
    if (!value) return;
    if (key === 'Почему') { why = value; return; }
    if (key === 'Пол') { gender = /муж/i.test(value) ? 'male' : 'female'; return; }
    if (key === 'Реальная вещь') { if (LAYER_KEYS.indexOf(value) !== -1) realKey = value; return; }
    if (LAYER_KEYS.indexOf(key) !== -1) {
      var cleaned = value.replace(SAME_ITEM_PREFIX_RE, '').trim();
      if (cleaned) layers[key] = cleaned;
    }
  });
  return { layers: layers, why: why, gender: gender, realKey: realKey };
}

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') {
    res.status(405).json({ error: 'Только POST' });
    return;
  }
  if (!process.env.SUPABASE_URL || !process.env.SUPABASE_SERVICE_ROLE_KEY) {
    res.status(503).json({ error: 'Вход и оплата пока не настроены на сервере.' });
    return;
  }

  var missing = [];
  if (!process.env.GIGACHAT_AUTH_KEY) missing.push('GIGACHAT_AUTH_KEY');
  if (!process.env.YANDEX_API_KEY) missing.push('YANDEX_API_KEY');
  if (!process.env.YANDEX_FOLDER_ID) missing.push('YANDEX_FOLDER_ID');
  if (missing.length) {
    res.status(503).json({ error: 'Сборка образа пока не настроена на сервере (нет ' + missing.join(', ') + ').' });
    return;
  }

  var user = await requireUser(req);
  if (!user) {
    res.status(401).json({ error: 'Нужно войти по email, чтобы собрать образ.' });
    return;
  }

  var allowed = await checkRateLimit(req, 'compose-look', { windowSeconds: 600, maxHits: 3 });
  if (!allowed) {
    res.status(429).json({ error: 'Слишком много запросов подряд. Попробуйте через несколько минут.' });
    return;
  }

  try {
    var entitled = await previewLookEntitlement(user.id);
    if (!entitled) {
      res.status(402).json({ error: 'Первый образ уже использован. Пополните баланс в личном кабинете, чтобы получить ещё один.' });
      return;
    }
  } catch (err) {
    console.error('compose-look entitlement check error:', err);
    res.status(500).json({ error: 'Не получилось проверить доступ. Попробуйте ещё раз.' });
    return;
  }

  try {
    var body = req.body || {};
    var dataUrl = body.image;
    if (!dataUrl || typeof dataUrl !== 'string') {
      res.status(400).json({ error: 'Нет фото в запросе.' });
      return;
    }
    var match = /^data:(image\/\w+);base64,(.+)$/.exec(dataUrl);
    if (!match) {
      res.status(400).json({ error: 'Некорректный формат фото.' });
      return;
    }
    var mime = match[1];
    var imageBuffer = Buffer.from(match[2], 'base64');
    if (imageBuffer.length > 4.2 * 1024 * 1024) {
      res.status(413).json({ error: 'Фото слишком большое — попробуйте другое или сожмите его.' });
      return;
    }

    var fit = typeof body.fit === 'string' ? body.fit.trim().slice(0, 200) : '';
    var itemHint = typeof body.itemHint === 'string' ? body.itemHint.trim().slice(0, 200) : '';
    var occasionLabel = OCCASION_LABELS[body.occasion] || null;
    var userText = fit
      ? 'Собери образ по фото. Рост и размер (по российской размерной сетке): ' + fit
      : 'Собери образ по фото.';
    if (itemHint) {
      userText += ' Уточнение от пользователя про вещь на фото — доверяй ему больше, чем своей ' +
        'догадке по картинке, если оно расходится с тем, что ты видишь: ' + itemHint;
    }
    if (occasionLabel) {
      userText += ' Повод, под который нужно собрать остальные слои (не угадывай другой по фото/вещи): ' + occasionLabel + '.';
    }

    var token = await getAccessToken();
    var fileId = await uploadFile(token, imageBuffer, mime);
    var raw = await chatWithImage(token, SYSTEM_PROMPT, userText, fileId);

    if (raw.trim().indexOf(NO_PERSON_MARKER) === 0) {
      res.status(422).json({ error: 'На фото не видно вещь, надетую на человеке — сфотографируйте себя в ней и загрузите ещё раз.' });
      return;
    }

    var finalRaw = raw;
    try {
      var verifyUserText = raw;
      if (itemHint) {
        verifyUserText += '\n\nПодсказка пользователя про вещь на фото (см. пункт 1 инструкции — доверяй ' +
          'ей больше, чем первому разбору и своей догадке по фото, если они расходятся): ' + itemHint;
      }
      var verifyRaw = await chatWithImage(token, VERIFY_PROMPT, verifyUserText, fileId);
      /* "OK" — короткий ответ (в разы короче полного разбора из 7 строк +
         "Почему"), поэтому сверяем по длине, а не точным словом — надёжнее
         при случайных вариациях пунктуации/регистра/языка ответа. */
      if (verifyRaw.trim().length >= 30) finalRaw = verifyRaw;
    } catch (verifyErr) {
      console.error('compose-look: самопроверка не удалась, используем первый ответ:', verifyErr);
    }

    var parsed = parseLayers(finalRaw);
    if (!parsed.layers['Низ']) {
      var fallbackOccasion = OCCASION_LABELS[body.occasion] ? body.occasion : '';
      parsed.layers['Низ'] = FALLBACK_BOTTOM[fallbackOccasion];
      console.warn('compose-look: GigaChat пропустил слой "Низ" (повод: ' + (body.occasion || 'не указан') + ') — подставлен запасной вариант');
    }
    var imageBase64 = await generateLookImage(buildLookImagePrompt(parsed.layers, fit, null, parsed.gender, parsed.realKey));

    /* Списываем только сейчас, когда генерация реально удалась. Если это
       спишет неудачно (крайне редкая гонка — баланс успели потратить между
       previewLookEntitlement выше и этим моментом), картинка уже нарисована
       и деньги за GigaChat/YandexART потрачены нами в любом случае — честнее
       всё равно отдать результат пользователю, чем показать ошибку после
       успешной генерации. Ошибку списания в этом случае просто логируем. */
    try {
      await chargeForLook(user.id);
    } catch (chargeErr) {
      console.error('compose-look: списание после успешной генерации не удалось:', chargeErr);
    }

    /* Сохраняем в «Мои образы» тоже только сейчас, после удачной генерации —
       по тем же причинам, что и списание выше. Сбой сохранения не должен
       превращать уже готовый результат в ошибку для клиентки — она всё
       равно увидит его на экране, просто он не останется в кабинете. */
    var savedLookId = null;
    try {
      var saved = await saveLook(user.id, {
        layers: parsed.layers,
        why: parsed.why,
        fit: fit,
        imageBuffer: Buffer.from(imageBase64, 'base64')
      });
      savedLookId = saved.id;
    } catch (saveErr) {
      console.error('compose-look: не удалось сохранить образ в кабинет:', saveErr);
    }

    res.status(200).json({
      layers: parsed.layers,
      why: parsed.why,
      image: 'data:image/jpeg;base64,' + imageBase64,
      savedLookId: savedLookId
    });
  } catch (err) {
    console.error('compose-look error:', err);
    res.status(502).json({ error: 'Не получилось собрать образ. Попробуйте ещё раз.' });
  }
};
