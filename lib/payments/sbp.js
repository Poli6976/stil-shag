/* ============================================================================
   Ручной канал оплаты СБП — временная мера на время, пока заявка в Robokassa
   на модерации (у самозанятого без ИП нет расчётного счёта для прямого
   эквайринга, поэтому вообще нужен агрегатор — см. историю решений про выбор
   Robokassa). В отличие от Robokassa здесь нет API и подписи webhook: клиент
   переводит деньги владельцу сайта напрямую по номеру телефона, а зачисление
   на депозит подтверждает вручную сам владелец через admin-sbp-orders.html
   (api/admin.js, action=sbp-confirm), сверив перевод в банковском приложении.
   ============================================================================ */

const crypto = require('crypto');

/* Короткий человекочитаемый код заказа — клиент указывает его в комментарии
   к переводу, чтобы владелец сайта мог сопоставить поступление с заявкой на
   сайте. 6 цифр с ведущими нулями (аналог generateInvId в robokassa.js, но
   короче — тут его вводит вручную живой человек, а не подставляет форма). */
function generateOrderCode() {
  return String(crypto.randomInt(0, 1000000)).padStart(6, '0');
}

module.exports = { generateOrderCode: generateOrderCode };
