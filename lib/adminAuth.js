/* ============================================================================
   Проверка ADMIN_KEY — общая для всех служебных действий владельца сайта
   (генерация кодов «Примерки»), см. api/admin.js. Раньше сравнение жило
   прямо внутри api/generate-code.js —
   вынесено сюда, когда появилось второе место, которому нужна та же проверка,
   чтобы не разойтись в двух копиях.
   ============================================================================ */

const crypto = require('crypto');

/* Пробелы по краям отбрасываем: при вставке ключа в поле легко прихватить пробел, а в заголовке
   X-Admin-Key (список партнёров) браузер их и так срезает — без этого список открывался, а все
   действия (выдать коды, удалить, добавить) отвечали «Неверный админ-ключ» (25.10.2026). */
function checkAdminKey(given) {
  if (!process.env.ADMIN_KEY) return false;
  var a = Buffer.from(String(given || '').trim());
  var b = Buffer.from(process.env.ADMIN_KEY.trim());
  return a.length === b.length && crypto.timingSafeEqual(a, b);
}

module.exports = { checkAdminKey: checkAdminKey };
